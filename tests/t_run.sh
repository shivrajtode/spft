#!/bin/bash
# Logic test for lib/run.sh (spft-run, which runs inside Debian): display choice, single copy, which tool
# version starts, the openbox "maximize" rule. Uses stand-in commands. Needs: bash, python3, pgrep, sed.
# On purpose in the tests: ok/bad always return 0, patterns are literal text, printf builds escapes.
# shellcheck disable=SC2015,SC2016,SC2012,SC2002,SC2059
set -u
REPO=$(cd "$(dirname "$0")/.." && pwd)
T=$(mktemp -d "${TMPDIR:-/tmp}/spft-run.XXXXXX")
mkdir -p "$T/bin" "$T/opt/SP_Flash_Tool_test/plugins" "$T/rt" "$T/home" "$T/etc-openbox"
: > "$T/opt/SP_Flash_Tool_test/flash_tool"

# a stand-in for Debian's /etc/xdg/openbox/rc.xml (same layout: the example rule sits inside a comment)
cat > "$T/etc-openbox/rc.xml" <<'XML'
<?xml version="1.0" encoding="UTF-8"?>

<!-- Do not edit this file, it will be overwritten on install.
        Copy the file to $HOME/.config/openbox/ instead. -->

<openbox_config xmlns="http://openbox.org/3.4/rc"
		xmlns:xi="http://www.w3.org/2001/XInclude">

<resistance>
  <strength>10</strength>
  <screen_edge_strength>20</screen_edge_strength>
</resistance>

<placement>
  <policy>Smart</policy>
  <center>yes</center>
</placement>

<applications>
<!--
  # this is an example with comments through out. use these to make your
  # own rules, but without the comments of course.

  <application name="the window's _OB_APP_NAME property (see obxprop)"
              class="the window's _OB_APP_CLASS property (see obxprop)"
               type="the window's _OB_APP_TYPE property (see obxprob)">
  # the type is one of: normal, dialog, splash, utility, menu, toolbar, dock,
  #    or desktop
    <decor>no</decor>
  </application>
-->
</applications>

</openbox_config>
XML

# stand-ins
cat > "$T/bin/box64" <<'EOF'
#!/bin/bash
echo "BOX64 args=[$*] DISPLAY=$DISPLAY NOMITSHM=$QT_X11_NO_MITSHM QTPLUG=${QT_PLUGIN_PATH:-unset}"
echo "BOX64 libpath=$BOX64_LD_LIBRARY_PATH"
echo "BOX64 preload=${BOX64_LD_PRELOAD:-unset}"
EOF
# uname -r says what FAKE_UNAME_R says (the kernel of the phone)
cat > "$T/bin/uname" <<'EOF'
#!/bin/bash
if [ "${1:-}" = -r ]; then echo "${FAKE_UNAME_R:-5.10.0}"; else exec /usr/bin/uname "$@"; fi
EOF
cat > "$T/bin/spft-gui" <<'EOF'
#!/bin/bash
echo "spft-gui called"
EOF
cat > "$T/bin/openbox" <<EOF
#!/bin/bash
if [ "\${1:-}" = --reconfigure ]; then echo "openbox reconfigure DISPLAY=\$DISPLAY" >> "$T/openbox-reconf.log"; exit 0; fi
echo "openbox started DISPLAY=\$DISPLAY" >> "$T/openbox.log"
sleep 25
EOF
chmod +x "$T/bin/"*

# the script under test, with its fixed paths moved into the work folder
sed -e "s#/opt#$T/opt#g" \
    -e "s#/tmp/\.X11-unix/X0#$T/X0#g" \
    -e "s#/tmp/spft-openbox0\.pid#$T/ob.pid#g" \
    -e "s#/tmp/openbox0\.log#$T/ob0.log#g" \
    -e "s#/tmp/runtime-root#$T/rt#g" \
    -e "s#/tmp/spft-fake-kernel#$T/fake-kernel#g" \
    -e "s#/tmp/spft-kernelfix\.so#$T/kernelfix.so#g" \
    -e "s#/etc/xdg/openbox#$T/etc-openbox#g" "$REPO/lib/run.sh" > "$T/spft-run"
if grep -n '/tmp/\|/opt\|/etc/' "$T/spft-run" | grep -v "$T"; then echo "NOTE: unreplaced fixed paths above"; fi

run() { env -i PATH="$T/bin:/usr/bin:/bin" HOME="$T/home" "$@" bash "$T/spft-run"; }
sock_up() { python3 -c 'import socket,sys,time; s=socket.socket(socket.AF_UNIX); s.bind(sys.argv[1]); time.sleep(40)' "$T/X0" & SOCKPID=$!; sleep 1; }
sock_down() { kill "$SOCKPID" 2>/dev/null; rm -f "$T/X0"; }

echo "=== 1. no X11 socket, auto -> VNC with a hint"
run; echo "exit=$?"

echo; echo "=== 2. X11 socket present, auto -> Termux:X11"
sock_up
run; echo "exit=$?"
echo "openbox starts so far: $(wc -l < "$T/openbox.log")"

echo; echo "=== 3. run again -> openbox must not be started twice"
run >/dev/null; echo "openbox starts so far: $(wc -l < "$T/openbox.log")"

echo; echo "=== 4. forced vnc while socket exists -> VNC"
run SPFT_DISPLAY=vnc; echo "exit=$?"
sock_down

echo; echo "=== 5. forced x11 without socket -> clear message, exit 1"
run SPFT_DISPLAY=x11; echo "exit=$?"

echo; echo "=== 6. bad mode -> message, exit 1"
run SPFT_DISPLAY=banana; echo "exit=$?"

echo; echo "=== 7. no tool installed -> tells you to run: spft tool, exit 1"
rm -f "$T/opt/SP_Flash_Tool_test/flash_tool"
run; echo "exit=$?"

echo; echo "=== 8. a copy is already running -> no second copy, exit 0"
: > "$T/opt/SP_Flash_Tool_test/flash_tool"
bash -c 'exec -a "box64 ./flash_tool" sleep 30' & DECOY=$!
sleep 1
run; echo "exit=$?"
kill "$DECOY" 2>/dev/null; wait "$DECOY" 2>/dev/null
echo "--- once it is gone, the tool starts normally again:"
run | grep -E '^BOX64 (args|libpath)='

echo; echo "=== 9. same, when only the process NAME is flash_tool (the command line was rewritten)"
mkdir -p "$T/ft"; cp "$(type -P sleep)" "$T/ft/flash_tool"
"$T/ft/flash_tool" 30 & DECOY=$!
sleep 1
run | head -n 1; echo "exit=${PIPESTATUS[0]}"
kill "$DECOY" 2>/dev/null; wait "$DECOY" 2>/dev/null

echo; echo "=== 10. Termux:X11, first start: rc.xml is made from Debian's default, plus one maximize rule"
sock_up
rm -f "$T/openbox.log" "$T/openbox-reconf.log" "$T/ob.pid" "$T/home/.config/openbox/rc.xml"
run SPFT_DISPLAY=x11 | grep -E '^(display:|starting SP Flash Tool)'
RC=$T/home/.config/openbox/rc.xml
python3 -I -c '
import sys, xml.dom.minidom as m
ns = "http://openbox.org/3.4/rc"
d = m.parse(sys.argv[1])
rules = d.getElementsByTagNameNS(ns, "application")
print("rc.xml is well-formed XML; rules:", len(rules))
for r in rules:
    print("  class=%s type=%s maximized=%s" % (r.getAttribute("class"), r.getAttribute("type"),
          r.getElementsByTagNameNS(ns, "maximized")[0].firstChild.data))
' "$RC"
if diff <(sed '/<application class="\*" type="normal">/d' "$RC") "$T/etc-openbox/rc.xml" >/dev/null; then
  echo "everything else in rc.xml is identical to Debian's default"; else echo "FAIL: rc.xml differs from the default in more than the rule"; fi
echo "openbox starts: $(wc -l < "$T/openbox.log")   reconfigures: $(cat "$T/openbox-reconf.log" 2>/dev/null | wc -l)"

echo; echo "=== 11. second start keeps an edited rc.xml and does not start openbox again"
echo '<!-- my own edit -->' >> "$RC"
cp "$RC" "$T/rc.before"
run SPFT_DISPLAY=x11 >/dev/null
if cmp -s "$RC" "$T/rc.before"; then echo "rc.xml untouched"; else echo "FAIL: rc.xml was rewritten"; fi
echo "openbox starts: $(wc -l < "$T/openbox.log")   reconfigures: $(cat "$T/openbox-reconf.log" 2>/dev/null | wc -l)"

echo; echo "=== 12. rc.xml made while openbox already runs -> openbox is told to reload it"
rm -f "$RC"
run SPFT_DISPLAY=x11 >/dev/null
echo "openbox starts: $(wc -l < "$T/openbox.log")   reconfigures: $(cat "$T/openbox-reconf.log" 2>/dev/null | wc -l)"
if [ -f "$RC" ]; then echo "rc.xml written again"; else echo "FAIL: no rc.xml"; fi

echo; echo "=== 13. Debian has no default rc.xml -> nothing is written, the tool still starts"
mv "$T/etc-openbox/rc.xml" "$T/etc-openbox/rc.xml.off"; rm -f "$RC"
run SPFT_DISPLAY=x11 | grep -c 'BOX64 args'
if [ -e "$RC" ]; then echo "FAIL: rc.xml was created"; else echo "ok: no rc.xml written"; fi
mv "$T/etc-openbox/rc.xml.off" "$T/etc-openbox/rc.xml"
sock_down

echo; echo "=== 14. /opt/spft-current decides which version starts"
rm -rf "$T/opt"; mkdir -p "$T/opt/v5" "$T/opt/v6"
: > "$T/opt/v5/flash_tool"; : > "$T/opt/v6/flash_tool"
ln -s v6 "$T/opt/spft-current"
run SPFT_DISPLAY=vnc | grep -E '^starting|BOX64 args' | sed "s#$T#\$T#g"
echo "--- and without the link, one of them is found:"
rm "$T/opt/spft-current"
run SPFT_DISPLAY=vnc | grep -c 'BOX64 args'

echo; echo "=== 15. the v6 program name (SPFlashToolV6) is found and started"
rm -rf "$T/opt"; mkdir -p "$T/opt/v6"; : > "$T/opt/v6/SPFlashToolV6"
run SPFT_DISPLAY=vnc | grep -E 'BOX64 args' | sed "s#$T#\$T#g"

echo; echo "=== 16. a running SPFlashToolV6 also blocks a second copy"
bash -c 'exec -a "box64 ./SPFlashToolV6" sleep 30' & DECOY=$!
sleep 1
run SPFT_DISPLAY=vnc | head -n 1; echo "exit=${PIPESTATUS[0]}"
kill "$DECOY" 2>/dev/null; wait "$DECOY" 2>/dev/null

echo; echo "=== 17. kernel 4.19.127: SP Flash Tool v5 wrongly rejects it (a text comparison), so it is shown 4.19.140"
rm -rf "$T/opt"; mkdir -p "$T/opt/v5"; : > "$T/opt/v5/flash_tool"
run SPFT_DISPLAY=vnc SPFT_LIBDIR="$REPO/lib" FAKE_UNAME_R=4.19.127-g8d3429bdb336 | grep -E '^kernel|^\(to turn|preload=|BOX64 args' | sed "s#$T#\$T#g"
echo "the file the library reads says: $(cat "$T/fake-kernel")"
if base64 -d "$REPO/lib/kernelfix.so.b64" | cmp -s - "$T/kernelfix.so"; then echo "ok: the library was decoded from lib/kernelfix.so.b64"; else echo "FAIL: the decoded library differs"; fi

echo; echo "=== 18. a kernel the tool accepts: nothing is shown, no library is loaded, and the file of the last run is gone"
run SPFT_DISPLAY=vnc SPFT_LIBDIR="$REPO/lib" FAKE_UNAME_R=5.10.0 | grep -E '^kernel|preload=' | sed "s#$T#\$T#g"
if [ -e "$T/fake-kernel" ]; then echo "FAIL: the old fake-kernel file is still there"; else echo "ok: no fake-kernel file"; fi

echo; echo "=== 19. an old kernel (4.14.186): left alone; SPFT_FAKE_KERNEL=5.4.0 forces a version"
run SPFT_DISPLAY=vnc SPFT_LIBDIR="$REPO/lib" FAKE_UNAME_R=4.14.186 | grep -E '^kernel|preload=' | sed "s#$T#\$T#g"
run SPFT_DISPLAY=vnc SPFT_LIBDIR="$REPO/lib" FAKE_UNAME_R=4.14.186 SPFT_FAKE_KERNEL=5.4.0 | grep -E '^kernel|preload=' | sed "s#$T#\$T#g"
echo "the file says: $(cat "$T/fake-kernel")"

echo; echo "=== 20. SPFT_FAKE_KERNEL=off turns the fix off, also for 4.19.127"
run SPFT_DISPLAY=vnc SPFT_LIBDIR="$REPO/lib" FAKE_UNAME_R=4.19.127 SPFT_FAKE_KERNEL=off | grep -E '^kernel|preload=' | sed "s#$T#\$T#g"
if [ -e "$T/fake-kernel" ]; then echo "FAIL: a fake-kernel file exists"; else echo "ok: no fake-kernel file"; fi

echo; echo "=== 21. a bad SPFT_FAKE_KERNEL is refused with a message, and the tool still starts"
run SPFT_DISPLAY=vnc SPFT_LIBDIR="$REPO/lib" FAKE_UNAME_R=4.19.127 'SPFT_FAKE_KERNEL=5.4;touch /tmp/pwned' | grep -E '^SPFT_FAKE|preload=|BOX64 args' | sed "s#$T#\$T#g"
if [ -e /tmp/pwned ]; then echo "FAIL: the value was run as a command"; rm -f /tmp/pwned; else echo "ok: nothing was run"; fi

echo; echo "=== 22. a BOX64_LD_PRELOAD that is already set stays, the fix comes first"
run SPFT_DISPLAY=vnc SPFT_LIBDIR="$REPO/lib" FAKE_UNAME_R=4.19.139 BOX64_LD_PRELOAD=/opt/other.so | grep -E 'preload=' | sed "s#$T#\$T#g"

echo; echo "=== 23. the kernel-fix files are not there (an old Debian setup): the tool simply starts"
mkdir -p "$T/emptylib"
run SPFT_DISPLAY=vnc SPFT_LIBDIR="$T/emptylib" FAKE_UNAME_R=4.19.127 | grep -E '^kernel|preload=|BOX64 args' | sed "s#$T#\$T#g"

pkill -f "sleep 25" 2>/dev/null
if grep -qF "$T" /proc/mounts; then echo "mounts under $T - not deleting"; else rm -rf "$T"; echo "cleaned up"; fi
